const lv = (l: Partial<BuildingLevelDef> & Pick<BuildingLevelDef, 'perks'>): BuildingLevelDef => ({
  upgradeCost: {},
  slots: 0,
  speed: 1,
  xp: 0,
  ...l,
});

/** Simple 1-level definition for decorations and paths. */
const deco = (
  id: string,
  name: string,
  coins: number,
  unlockLevel: number,
  charm: number,
  description: string,
  extra: Partial<BuildingDef> = {},
): BuildingDef => ({
  id,
  name,
  category: 'decoration',
  description,
  footprint: [1, 1],
  unlockLevel,
  cost: { coins },
  xp: 1,
  levels: [lv({ perks: [`+${charm} charm`] })],
  archetype: `deco:${id}`,
  charm,
  sellRefund: 0.5,
  ...extra,
});

