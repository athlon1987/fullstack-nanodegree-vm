// Generates the field reference in docs/CONTENT_SCHEMA.md from the live validators, so the
// documentation can never drift from what the game actually accepts.
// Run: npx vite-node scripts/content/schema-doc.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { countrySchema, indexSchema, moduleSchema, worldSchema } from '../../src/platform/content/schema';
import type { Schema } from '../../src/platform/validate';

const lines: string[] = [];
function walk(s: Schema<unknown>, path: string, depth: number) {
  if (depth > 6) return;
  if (s.shape) {
    for (const [k, f] of Object.entries(s.shape)) {
      const p = path ? `${path}.${k}` : k;
      lines.push(`| \`${p}\` | ${f.optional ? 'optional' : '**required**'} | ${desc(f).replace(/\|/g, '\\|')} |`);
      walk(f, p, depth + 1);
    }
  } else if (s.item) walk(s.item, `${path}[]`, depth + 1);
  else if (s.value) walk(s.value, `${path}{}`, depth + 1);
  else if (s.variants) for (const [k, v] of Object.entries(s.variants)) walk(v, `${path}<${k}>`, depth + 1);
}
function desc(s: Schema<unknown>): string {
  if (s.item) return `${s.describe()} of ${s.item.shape ? 'objects' : s.item.describe()}`;
  if (s.value) return `${s.describe()} → ${s.value.shape ? 'object' : s.value.describe()}`;
  return s.describe();
}

const out: string[] = [];
for (const [name, schema] of [['Content index (`content/index.json`)', indexSchema], ['Country (`content/countries/*.json`)', countrySchema], ['World pack (`content/worlds/*.json`)', worldSchema], ['Module (`content/modules/*.json`)', moduleSchema]] as const) {
  lines.length = 0;
  walk(schema as Schema<unknown>, '', 0);
  out.push(`### ${name}\n\n| Field | | Type |\n|---|---|---|\n${lines.join('\n')}\n`);
}
const file = join(import.meta.dirname, '../../docs/CONTENT_SCHEMA.md');
const doc = readFileSync(file, 'utf8');
const start = '<!-- schema:begin -->';
const end = '<!-- schema:end -->';
const next = `${doc.slice(0, doc.indexOf(start) + start.length)}\n_Generated by \`scripts/content/schema-doc.ts\` from \`src/platform/content/schema.ts\`. Do not edit by hand._\n\n${out.join('\n')}\n${doc.slice(doc.indexOf(end))}`;
writeFileSync(file, next);
console.log('CONTENT_SCHEMA.md reference updated');
