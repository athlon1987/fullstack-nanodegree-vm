#!/usr/bin/env python3
"""Synthesize every dialogue line with Kokoro (Apache-2.0 neural TTS, runs locally on CPU).

Reads   audio/dialogue.json
Writes  audio/vo/<id>.flac             48 kHz mono, trimmed, dry (no room/FX — the mixer adds those); committed
        audio/out/vo/<id>.wav          the same as float WAV (scratch)
        src/dialogue.gen.js            {id: {who, text, dur}} consumed by src/timeline.js
        assets/voice_env.json          loudness envelope per line at 24 fps (drives mouth/head animation)

Model files (not committed, ~350 MB) are expected in .cache/kokoro/:
  https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.onnx
  https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin
"""
import json, sys
from math import gcd
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

ROOT = Path(__file__).resolve().parent.parent
SR_OUT = 48000
FPS = 24


def f0_median(x, sr):
    """Rough median fundamental (Hz) via autocorrelation on voiced frames."""
    n = int(sr * 0.04); hop = int(sr * 0.01); out = []
    for i in range(0, len(x) - n, hop):
        fr = x[i:i + n] * np.hanning(n)
        if np.sqrt(np.mean(fr ** 2)) < 0.02: continue
        ac = np.correlate(fr, fr, 'full')[n - 1:]
        lo, hi = int(sr / 500), int(sr / 70)
        if ac[0] <= 0: continue
        k = lo + int(np.argmax(ac[lo:hi]))
        if ac[k] / ac[0] > 0.45: out.append(sr / k)
    return float(np.median(out)) if out else 0.0


def trim(x, sr, thresh=0.008, pad=0.03):
    idx = np.where(np.abs(x) > thresh)[0]
    if not len(idx): return x
    a = max(0, idx[0] - int(pad * sr)); b = min(len(x), idx[-1] + int(pad * sr * 2))
    y = x[a:b].copy()
    f = int(0.008 * sr)
    y[:f] *= np.linspace(0, 1, f); y[-f:] *= np.linspace(1, 0, f)
    return y


def envelope(x, sr):
    hop = sr // FPS
    n = int(np.ceil(len(x) / hop))
    e = np.array([np.sqrt(np.mean(x[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
    e = e / (np.percentile(e, 95) + 1e-9)
    e = np.clip(e, 0, 1) ** 0.7
    return [round(float(v), 3) for v in e]


def main():
    from kokoro_onnx import Kokoro
    cfg = json.loads((ROOT / 'audio/dialogue.json').read_text())
    only = set(sys.argv[1:])
    k = Kokoro(str(ROOT / '.cache/kokoro/kokoro-v1.0.onnx'), str(ROOT / '.cache/kokoro/voices-v1.0.bin'))
    out_dir = ROOT / 'audio/out/vo'; out_dir.mkdir(parents=True, exist_ok=True)
    meta_path = out_dir / 'meta.json'
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
    env_path = ROOT / 'assets/voice_env.json'
    envs = json.loads(env_path.read_text()) if env_path.exists() else {}

    for ln in cfg['lines']:
        if only and ln['id'] not in only: continue
        cast = {**cfg['cast'][ln['who']], **{kk: ln[kk] for kk in ('voice', 'speed', 'pitch') if kk in ln}}
        pitch = cast.get('pitch', 1.0)
        # pitch>1: synthesize slower, then play back faster -> same pace, higher pitch AND formants (smaller speaker)
        x, sr = k.create(ln['text'], voice=cast['voice'], speed=cast['speed'] / pitch, lang='en-gb' if cast['voice'].startswith('b') else 'en-us')
        x = np.asarray(x, dtype=np.float32)
        up, down = SR_OUT, int(round(sr * pitch))
        g = gcd(up, down)
        y = resample_poly(x, up // g, down // g).astype(np.float32)
        y = trim(y, SR_OUT)
        y = y / (np.abs(y).max() + 1e-9) * 0.7
        sf.write(out_dir / f"{ln['id']}.wav", y, SR_OUT, subtype='FLOAT')
        (ROOT / 'audio/vo').mkdir(exist_ok=True)
        sf.write(ROOT / 'audio/vo' / f"{ln['id']}.flac", y, SR_OUT, subtype='PCM_16')   # committed copy the mixer reads
        meta[ln['id']] = {'who': ln['who'], 'text': ln['text'], 'dur': round(len(y) / SR_OUT, 3), 'f0': round(f0_median(y, SR_OUT), 1), 'voice': cast['voice']}
        envs[ln['id']] = envelope(y, SR_OUT)
        print(f"{ln['id']:13s} {ln['who']:9s} {meta[ln['id']]['dur']:5.2f}s  f0={meta[ln['id']]['f0']:5.1f}Hz  {ln['text']}")

    meta_path.write_text(json.dumps(meta, indent=1))
    env_path.write_text(json.dumps(envs, separators=(',', ':')))
    order = [l['id'] for l in cfg['lines'] if l['id'] in meta]
    js = "// GENERATED by audio/tts.py — do not edit. Durations (seconds) of the synthesized dialogue.\nexport const DIALOGUE = {\n"
    js += ''.join(f"  {json.dumps(i)}: {json.dumps({kk: meta[i][kk] for kk in ('who', 'text', 'dur')}, ensure_ascii=False)},\n" for i in order)
    js += "};\n"
    (ROOT / 'src/dialogue.gen.js').write_text(js)
    print(f"total speech: {sum(meta[i]['dur'] for i in order):.1f}s in {len(order)} lines")


if __name__ == '__main__':
    main()
