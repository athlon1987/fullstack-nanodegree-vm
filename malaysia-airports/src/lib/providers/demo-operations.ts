/**
 * Demo providers for queue estimates and car park availability.
 *
 * Both are deterministic functions of (airport, local time): a daily curve with morning and
 * evening peaks plus seeded noise per 10-minute bucket. Every value carries `isDemo: true` and
 * must be shown with the demonstration label. Neither reads the clock: pass `now` in.
 */
import { getAirport } from '@/content/airports';
import { lt } from '@/content/values';
import type { LocalizedText, Notice, TerminalId } from '@/content/types';
import { dateKey, minutesOfDay, toDate, toIsoWithOffset, type Instant } from '@/lib/time';
import { OPS_SERVICES, type OpsServiceId } from './ops-services';
import { seededRandom } from './random';
import type {
  ParkingAvailability,
  ParkingAvailabilityProvider,
  ProviderMeta,
  WaitCheckpoint,
  WaitTime,
  WaitTimeProvider,
} from './types';

const CHECKPOINTS: { checkpoint: WaitCheckpoint; base: number; peak: number }[] = [
  { checkpoint: 'check-in', base: 5, peak: 18 },
  { checkpoint: 'security', base: 3, peak: 14 },
  { checkpoint: 'immigration-departure', base: 4, peak: 20 },
  { checkpoint: 'immigration-arrival', base: 6, peak: 28 },
  { checkpoint: 'customs', base: 2, peak: 8 },
  { checkpoint: 'taxi-queue', base: 3, peak: 15 },
];

/** How busy an airport is at a local minute of the day, from 0 (quiet) to 1 (peak). */
export function demoBusyness(minuteOfDay: number): number {
  const bump = (centre: number, width: number): number => Math.exp(-(((minuteOfDay - centre) / width) ** 2));
  const value = 0.12 + 0.88 * Math.max(bump(450, 110), bump(1140, 140), 0.55 * bump(780, 120));
  return Math.min(1, Math.max(0, value));
}

function waitMinutes(airport: string, terminal: string, checkpoint: WaitCheckpoint, base: number, peak: number, date: string, minute: number): number {
  const bucket = Math.floor(minute / 10);
  const noise = seededRandom(`${airport}|${terminal}|${checkpoint}|${date}|${bucket}`)();
  return Math.max(1, Math.round(base + peak * demoBusyness(bucket * 10) + noise * 4 - 2));
}

function demoMeta(now: Date, what: string, en: string, ms: string): ProviderMeta {
  return {
    mode: 'demo',
    label: lt('Demonstration data', 'Data demonstrasi'),
    generatedAt: toIsoWithOffset(now),
    refreshSeconds: 60,
    source: `Simulated ${what} generated by this prototype. Not connected to any airport system.`,
    disclaimer: lt(en, ms),
  };
}

/** Simulated queue estimates. Create one per instant: `new DemoWaitTimeProvider(now)`. */
export class DemoWaitTimeProvider implements WaitTimeProvider {
  readonly now: Date;

  constructor(now: Instant) {
    this.now = new Date(toDate(now).getTime());
  }

  meta(): ProviderMeta {
    return demoMeta(
      this.now,
      'wait times',
      'Wait times are simulated for this prototype. They are not live.',
      'Masa menunggu disimulasikan untuk prototaip ini. Ia bukan maklumat langsung.',
    );
  }

  /** Synchronous form of `getWaitTimes`. */
  getWaitTimesSync(query: { airport: string; terminal?: TerminalId }): WaitTime[] {
    const airport = getAirport(query.airport);
    if (!airport || airport.depth === 'listing') return [];
    const zone = airport.timezone;
    const date = dateKey(this.now, zone);
    const minute = minutesOfDay(this.now, zone);
    const terminals = airport.terminals.filter((terminal) => !query.terminal || terminal.id === query.terminal);
    const scale = airport.slug === 'kul' ? 1 : airport.depth === 'full' ? 0.7 : 0.4;

    return terminals.flatMap((terminal) =>
      CHECKPOINTS.map(({ checkpoint, base, peak }) => {
        const minutes = waitMinutes(airport.slug, terminal.id, checkpoint, base * scale, peak * scale, date, minute);
        const later = waitMinutes(airport.slug, terminal.id, checkpoint, base * scale, peak * scale, date, Math.min(1439, minute + 30));
        const change = later - minutes;
        return {
          airport: airport.slug,
          terminal: terminal.id,
          checkpoint,
          minutes,
          level: minutes < 10 ? 'short' : minutes < 20 ? 'moderate' : 'long',
          trend: change >= 3 ? 'rising' : change <= -3 ? 'falling' : 'steady',
          updatedAt: toIsoWithOffset(this.now, zone),
          isDemo: true,
        } satisfies WaitTime;
      }),
    );
  }

  async getWaitTimes(query: { airport: string; terminal?: TerminalId }): Promise<WaitTime[]> {
    return this.getWaitTimesSync(query);
  }
}

/** Simulated car park availability. Create one per instant: `new DemoParkingAvailabilityProvider(now)`. */
export class DemoParkingAvailabilityProvider implements ParkingAvailabilityProvider {
  readonly now: Date;

  constructor(now: Instant) {
    this.now = new Date(toDate(now).getTime());
  }

  meta(): ProviderMeta {
    return demoMeta(
      this.now,
      'car park availability',
      'Car park availability is simulated for this prototype. It is not live.',
      'Ketersediaan tempat letak kereta disimulasikan untuk prototaip ini. Ia bukan maklumat langsung.',
    );
  }

  /** Synchronous form of `getAvailability`. */
  getAvailabilitySync(query: { airport: string; carParks: readonly { id: string; bays?: number }[] }): ParkingAvailability[] {
    const airport = getAirport(query.airport);
    const zone = airport?.timezone;
    const date = dateKey(this.now, zone);
    const minute = minutesOfDay(this.now, zone);
    const bucket = Math.floor(minute / 15);

    return query.carParks.map((carPark) => {
      const noise = seededRandom(`${query.airport}|${carPark.id}|${date}|${bucket}`)();
      const percentFull = Math.min(99, Math.max(8, Math.round(35 + 50 * demoBusyness(bucket * 15) + noise * 10 - 5)));
      const availability: ParkingAvailability = {
        carParkId: carPark.id,
        percentFull,
        level: percentFull >= 97 ? 'full' : percentFull >= 85 ? 'nearly-full' : percentFull >= 60 ? 'filling' : 'plenty',
        updatedAt: toIsoWithOffset(this.now, zone),
        isDemo: true,
      };
      if (carPark.bays !== undefined) availability.availableBays = Math.round((carPark.bays * (100 - percentFull)) / 100);
      return availability;
    });
  }

  async getAvailability(query: { airport: string; carParks: readonly { id: string; bays?: number }[] }): Promise<ParkingAvailability[]> {
    return this.getAvailabilitySync(query);
  }
}

/* ------------------------------------------------------------------------------------------
 * Operational status lines (BR-08): Aerotrain, inter-terminal train, shuttle, immigration
 * --------------------------------------------------------------------------------------- */

export { OPS_SERVICE_IDS, type OpsServiceId } from './ops-services';

/** The services that exist at an airport, in display order. */
export function opsServicesFor(airport: string): OpsServiceId[] {
  return OPS_SERVICES.filter((service) => service.airports.includes(airport)).map((service) => service.id);
}

/** Where a service stands in our sources at an instant. */
export type OpsState =
  /** A notice about the service is in effect now. */
  | 'notice'
  /** A notice about the service starts within the next 14 days. */
  | 'planned'
  /**
   * No notice about the service in our sources, and no live operations feed (OOS-02): its state
   * cannot be known, so the line says "Status not available" and where to check (round 4,
   * re-review 6.1.1). It is never "no disruption": a dated notice set is not a current source.
   */
  | 'unknown';

/** One status line. */
export interface OpsStatusLine {
  service: OpsServiceId;
  name: LocalizedText;
  terminal?: TerminalId;
  state: OpsState;
  /** The notice behind a `notice` or `planned` state. */
  notice?: Pick<Notice, 'id' | 'title' | 'body' | 'validFrom' | 'validTo' | 'provenance' | 'sources' | 'asOf'>;
  /**
   * What the line rests on. Always `notices` until a live operations feed exists: the line was
   * worked out from dated notices in the build, not checked against anything live, so it carries
   * no "checked hh:mm" time (round 4, re-review 6.1.1).
   */
  basis: 'notices';
  /** The latest `asOf` among the airport's notices (`YYYY`, `YYYY-MM` or `YYYY-MM-DD`), when any has one. */
  noticesAsOf?: string;
  /** Demo queue estimates for the service's checkpoints (always `isDemo`). */
  waits: WaitTime[];
}

const PLANNED_HORIZON_MS = 14 * 24 * 60 * 60 * 1000;

/** The network notice that only says the prototype's data is simulated; it is about no service. */
const PROTOTYPE_NOTICE_ID = 'prototype-demo-data';

/**
 * The latest `asOf` among an airport's own notices (and network notices about operations), for
 * "Based on notices published up to …". `undefined` when none is dated. Pure.
 */
export function noticesPublishedUpTo(notices: readonly Notice[], airport: string): string | undefined {
  const slug = getAirport(airport)?.slug ?? airport;
  let latest: string | undefined;
  for (const notice of notices) {
    if (notice.id === PROTOTYPE_NOTICE_ID || !notice.asOf) continue;
    if (notice.airport && notice.airport !== slug) continue;
    // `asOf` values are ISO prefixes, so the string order is the date order.
    if (latest === undefined || notice.asOf > latest) latest = notice.asOf;
  }
  return latest;
}

/**
 * Status lines for an airport's services at `now`, fed by its notices (pass `getNotices(airport)`
 * from the content layer) until a live operations feed exists. Pure.
 *
 * @example opsStatus({ airport: 'kul', notices, now, services: ['aerotrain'] })
 */
export function opsStatus(input: {
  airport: string;
  notices: readonly Notice[];
  now: Instant;
  /** Limit to these services (in this order). Default: every service at the airport. */
  services?: readonly OpsServiceId[];
  /** Only services of this terminal (and those not tied to one). */
  terminal?: TerminalId;
  /** Add demo queue estimates. Default true. */
  waits?: boolean;
}): OpsStatusLine[] {
  const airport = getAirport(input.airport);
  if (!airport) return [];
  const now = toDate(input.now);
  const time = now.getTime();
  const noticesAsOf = noticesPublishedUpTo(input.notices, airport.slug);
  const wanted = input.services ?? opsServicesFor(airport.slug);
  const waitProvider = input.waits === false ? null : new DemoWaitTimeProvider(now);
  const lines: OpsStatusLine[] = [];
  for (const id of wanted) {
    const service = OPS_SERVICES.find((item) => item.id === id);
    if (!service || !service.airports.includes(airport.slug)) continue;
    if (input.terminal && service.terminal && service.terminal !== input.terminal) continue;
    const relevant = input.notices.filter((notice) => {
      if (notice.airport && notice.airport !== airport.slug) return false;
      if (notice.provenance === 'demo' && notice.id === PROTOTYPE_NOTICE_ID) return false;
      return service.pattern.test(notice.id) || service.pattern.test(notice.title.en);
    });
    const active = relevant.find((notice) => {
      const from = notice.validFrom ? Date.parse(notice.validFrom) : -Infinity;
      const to = notice.validTo ? Date.parse(notice.validTo) : Infinity;
      return time >= from && time <= to;
    });
    const planned = active
      ? undefined
      : relevant
          .filter((notice) => notice.validFrom && Date.parse(notice.validFrom) > time && Date.parse(notice.validFrom) - time <= PLANNED_HORIZON_MS)
          .sort((a, b) => Date.parse(a.validFrom as string) - Date.parse(b.validFrom as string))[0];
    const notice = active ?? planned;
    const terminals = service.terminal ? [service.terminal] : input.terminal ? [input.terminal] : airport.terminals.map((item) => item.id);
    const waits =
      waitProvider && service.waits
        ? waitProvider
            .getWaitTimesSync({ airport: airport.slug })
            .filter((wait) => service.waits?.includes(wait.checkpoint) && terminals.includes(wait.terminal))
        : [];
    lines.push({
      service: service.id,
      name: service.name,
      ...(service.terminal ? { terminal: service.terminal } : {}),
      state: active ? 'notice' : planned ? 'planned' : 'unknown',
      ...(notice
        ? {
            notice: {
              id: notice.id,
              title: notice.title,
              body: notice.body,
              validFrom: notice.validFrom,
              validTo: notice.validTo,
              provenance: notice.provenance,
              sources: notice.sources,
              asOf: notice.asOf,
            },
          }
        : {}),
      basis: 'notices',
      ...(noticesAsOf ? { noticesAsOf } : {}),
      waits,
    });
  }
  return lines;
}
